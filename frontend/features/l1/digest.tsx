"use client";

import { ArrowRight, Moon, Wrench } from "lucide-react";
import Link from "next/link";
import type { DigestItem } from "@/contracts";
import { Button } from "@/components/ui/button";
import { useLookup } from "@/components/brain/names";
import { CritBadge, EmptyState, Kpi, PageHeader, QueryView, Section } from "@/components/brain/primitives";
import { useDigest, useOp } from "@/lib/api/hooks";
import { useCurrentUser } from "@/lib/auth";
import { dateTime } from "@/lib/format";

function ItemList({ items, empty }: { items: DigestItem[]; empty: string }) {
  if (!items.length) return <p className="text-xs text-muted-foreground">{empty}</p>;
  return (
    <ul className="divide-y">
      {items.map((i) => (
        <li key={i.id} className="flex items-start gap-3 py-2.5">
          <CritBadge level={i.criticality} />
          <div className="min-w-0 flex-1">
            <div className="text-sm font-medium">{i.title}</div>
            <div className="text-xs text-muted-foreground">{i.detail}</div>
          </div>
          {i.href && (
            <Link href={i.href} className="shrink-0 text-xs text-primary hover:underline" aria-label={`Open ${i.title}`}>
              Open <ArrowRight className="inline size-3" />
            </Link>
          )}
        </li>
      ))}
    </ul>
  );
}

export function Digest() {
  const digest = useDigest();
  const lookup = useLookup();
  const { user } = useCurrentUser();
  const run = useOp("runOvernightReview", { success: "Overnight review finished" });
  return (
    <div>
      <PageHeader
        title="Morning digest"
        description="What happened overnight: runs, failures found, fixes applied automatically at C0 and C1, and changes waiting for a decision."
        actions={
          user && user.tier !== "L3" ? (
            <Button variant="outline" size="sm" onClick={() => run.mutate({})} disabled={run.isPending}>
              <Moon /> Run overnight review now
            </Button>
          ) : null
        }
      />
      <QueryView query={digest} empty={<EmptyState title="No digest yet" description="The Quality Supervisor writes one every night at 02:00." />}>
        {(d) => {
          if (!d) return null;
          const fixes = d.items.filter((i) => i.kind === "auto_fix");
          const drafted = d.items.filter((i) => i.kind === "drafted");
          const waiting = d.items.filter((i) => i.kind === "waiting");
          return (
            <div className="space-y-4">
              <p className="text-xs text-muted-foreground">
                Generated by {d.generatedBy} at {dateTime(d.generatedAt, lookup.tz)} for {d.date}.
              </p>
              <div className="grid grid-cols-2 gap-3 md:grid-cols-5">
                <Kpi label="Runs reviewed" value={d.runs} />
                <Kpi label="Failures found" value={d.failures} tone={d.failures ? "warn" : "ok"} />
                <Kpi label="Fixes applied (C0, C1)" value={fixes.length} tone="ok" />
                <Kpi label="Drafted for review" value={drafted.length} />
                <Kpi label="Waiting on approvals" value={waiting.length} />
              </div>
              <div className="grid gap-4 lg:grid-cols-2">
                <Section title={<span className="flex items-center gap-1.5"><Wrench className="size-3.5" /> Applied automatically</span>} description="Routine and low changes. Logged, reversible, tests passing.">
                  <div data-testid="digest-applied">
                    <ItemList items={fixes} empty="No automatic fixes last night." />
                  </div>
                </Section>
                <Section title="Drafted, needs a decision" description="C2 and above go to the right person through the criticality matrix.">
                  <div data-testid="digest-drafted">
                    <ItemList items={drafted} empty="Nothing drafted." />
                  </div>
                </Section>
                <Section title="Waiting on approvals">
                  <ItemList items={waiting} empty="Inbox zero." />
                </Section>
                <Section title="Failures found, by class">
                  {d.failureClasses.length === 0 ? (
                    <p className="text-xs text-muted-foreground">No failures.</p>
                  ) : (
                    <ul className="space-y-2">
                      {d.failureClasses.map((f) => (
                        <li key={f.name} className="text-xs">
                          <div className="mb-1 flex justify-between">
                            <span className="capitalize">{f.name}</span>
                            <span className="tabular">{f.count}</span>
                          </div>
                          <div className="h-1.5 rounded-full bg-muted">
                            <div className="h-1.5 rounded-full bg-warn" style={{ width: `${(f.count / Math.max(...d.failureClasses.map((x) => x.count))) * 100}%` }} />
                          </div>
                        </li>
                      ))}
                    </ul>
                  )}
                </Section>
              </div>
            </div>
          );
        }}
      </QueryView>
    </div>
  );
}
